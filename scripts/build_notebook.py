"""Build and execute the demand-forecasting walkthrough notebook.

python scripts/build_notebook.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import nbformat as nbf
from nbclient import NotebookClient

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

OUTPUT = ROOT / "notebooks" / "01_demand_forecasting.ipynb"


def build() -> nbf.NotebookNode:
    notebook = nbf.v4.new_notebook()
    notebook["cells"] = [
        nbf.v4.new_markdown_cell(
            "# Hourly bike-share demand: analysis walkthrough\n\n"
            "This notebook reads the artefacts written by `python run.py all` and walks "
            "through the demand profile, the model ladder, the time-based hold-out and the "
            "error structure. It is generated by `scripts/build_notebook.py`, so the prose "
            "and the numbers cannot drift apart."
        ),
        nbf.v4.new_code_cell(
            "import json, sys\n"
            "from pathlib import Path\n"
            "\n"
            "import pandas as pd\n"
            "from IPython.display import Image, display\n"
            "\n"
            "ROOT = Path.cwd().parent if Path.cwd().name == 'notebooks' else Path.cwd()\n"
            "sys.path.insert(0, str(ROOT / 'src'))\n"
            "pd.set_option('display.width', 120)\n"
            "pd.set_option('display.max_columns', 30)"
        ),
        nbf.v4.new_markdown_cell("## 1. Headline numbers"),
        nbf.v4.new_code_cell(
            "eda = json.loads((ROOT / 'reports/eda_summary.json').read_text(encoding='utf-8'))\n"
            "metrics = json.loads((ROOT / 'reports/metrics.json').read_text(encoding='utf-8'))\n"
            "diagnostics = json.loads(\n"
            "    (ROOT / 'reports/diagnostics_summary.json').read_text(encoding='utf-8')\n"
            ")\n"
            "clean = json.loads((ROOT / 'reports/clean_report.json').read_text(encoding='utf-8'))\n"
            "test = metrics['test']\n"
            "pd.Series({\n"
            "    'hours modelled': f\"{eda['hours']:,}\",\n"
            "    'period': f\"{eda['date_min'][:10]} to {eda['date_max'][:10]}\",\n"
            "    'total rentals': f\"{eda['total_rentals']:,}\",\n"
            "    'missing hours on the grid': clean['missing_hours'],\n"
            "    'selected model': metrics['selected_model'],\n"
            "    'hold-out RMSE': test['rmse'],\n"
            "    'hold-out R2': test['r2'],\n"
            "    'improvement over weekly baseline': f\"{metrics['improvement_vs_naive_pct']}%\",\n"
            "}, name='value')"
        ),
        nbf.v4.new_markdown_cell(
            "Two cleaning decisions matter before any modelling: the 165 hours absent "
            "from the published table are reindexed onto a complete grid, and the "
            "`casual`/`registered` component columns are dropped because they sum to the "
            "target and would leak it."
        ),
        nbf.v4.new_markdown_cell("## 2. The shape of demand"),
        nbf.v4.new_code_cell(
            "display(Image(filename=str(ROOT / 'reports/figures/02_hourly_profile.png')))"
        ),
        nbf.v4.new_code_cell(
            "display(Image(filename=str(ROOT / 'reports/figures/03_month_hour_heatmap.png')))"
        ),
        nbf.v4.new_code_cell(
            "display(Image(filename=str(ROOT / 'reports/figures/04_weather_effects.png')))"
        ),
        nbf.v4.new_markdown_cell(
            "Demand has two commute peaks around 08:00 and 17:00, a summer maximum and a "
            "clear weather gradient. Any model that ignores the calendar starts from a "
            "handicap; the seasonal-naive baseline captures exactly that structure."
        ),
        nbf.v4.new_markdown_cell("## 3. Model ladder"),
        nbf.v4.new_code_cell(
            "cv = pd.DataFrame(metrics['cv']).T[['rmse_mean', 'rmse_std', 'mae_mean']]\n"
            "test_all = pd.DataFrame(metrics['test_all_models']).T[['rmse', 'mae', 'r2', 'mape']]\n"
            "display(cv.round(2))\n"
            "test_all.round(3)"
        ),
        nbf.v4.new_code_cell(
            "display(Image(filename=str(ROOT / 'reports/figures/09_model_comparison.png')))"
        ),
        nbf.v4.new_markdown_cell(
            "Model selection uses expanding-window validation on the training period only. "
            "The hold-out quarter from 2012-10-01 is scored once, after selection."
        ),
        nbf.v4.new_markdown_cell("## 4. One hold-out week"),
        nbf.v4.new_code_cell(
            "display(Image(filename=str(ROOT / 'reports/figures/15_forecast_week.png')))"
        ),
        nbf.v4.new_code_cell(
            "display(Image(filename=str(ROOT / 'reports/figures/10_predicted_vs_actual.png')))"
        ),
        nbf.v4.new_markdown_cell(
            "The model tracks the daily shape closely and flattens the tallest evening "
            "peaks: fitting on the log scale trades a little peak height for stability "
            "across the rest of the day."
        ),
        nbf.v4.new_markdown_cell("## 5. Where the errors concentrate"),
        nbf.v4.new_code_cell(
            "display(Image(filename=str(ROOT / 'reports/figures/12_error_by_hour.png')))"
        ),
        nbf.v4.new_code_cell(
            "display(Image(filename=str(ROOT / 'reports/figures/13_error_by_weather.png')))"
        ),
        nbf.v4.new_code_cell(
            "display(Image(filename=str(ROOT / 'reports/figures/11_residuals_over_time.png')))"
        ),
        nbf.v4.new_code_cell(
            "pd.Series({\n"
            "    'worst hour': f\"{diagnostics['worst_hour']['hour']:02d}:00\",\n"
            "    'MAE at worst hour': diagnostics['worst_hour']['mae'],\n"
            "    'best hour': f\"{diagnostics['best_hour']['hour']:02d}:00\",\n"
            "    'MAE at best hour': diagnostics['best_hour']['mae'],\n"
            "    'share within 25% of actual': f\"{diagnostics['share_within_25pct']:.1%}\",\n"
            "    'daily bias range': diagnostics['daily_bias_range'],\n"
            "}, name='value')"
        ),
        nbf.v4.new_markdown_cell(
            "Absolute error is concentrated in the evening peak, which is also where the "
            "operational decisions are made. Reporting a single RMSE hides that; the "
            "percentage-within-band figure is the fairer summary for capacity planning."
        ),
        nbf.v4.new_markdown_cell("## 6. What drives the forecast"),
        nbf.v4.new_code_cell("pd.DataFrame(metrics['feature_importance']).head(10).round(4)"),
        nbf.v4.new_code_cell(
            "display(Image(filename=str(ROOT / 'reports/figures/14_feature_importance.png')))"
        ),
        nbf.v4.new_markdown_cell(
            "Permutation importance on the hold-out quarter puts recent demand first, "
            "with the weekly lag and hour encodings filling in the shape."
        ),
        nbf.v4.new_markdown_cell(
            "## 7. Reproducing the results\n\n"
            "`reports/REPORT.md` carries the full narrative and `reports/model_card.md` the "
            "intended-use statement. Rebuild everything with:\n\n"
            "```bash\npython run.py all\n```"
        ),
    ]
    return notebook


def main() -> int:
    notebook = build()
    client = NotebookClient(notebook, timeout=600, kernel_name="python3")
    client.execute()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    nbf.write(notebook, OUTPUT)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
